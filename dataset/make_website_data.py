"""
make_website_data.py
--------------------
Reads dataset/case_haveli.txt (the file the C++ program loads) and writes:
  - dataset/case_haveli.json        (a readable copy of the same case)
  - website/js/caseData.js             (the same case as a JavaScript object)

Why: the browser cannot easily read a local .txt file when you open index.html by
double-clicking it, so the website gets its own copy of the data inside a .js file.
Running this script keeps the C++ data and the website data identical.

Usage (from the Detective_Mystery_Game folder):
    python dataset/make_website_data.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "case_haveli.txt")
OUT_JSON = os.path.join(HERE, "case_haveli.json")
OUT_JS = os.path.join(HERE, "..", "website", "js", "caseData.js")


def id_list(text):
    """'3,5' -> [3, 5]   and   '-' -> []"""
    return [] if text.strip() == "-" else [int(x) for x in text.split(",")]


def main():
    case = {"suspects": [], "nodes": []}
    with open(SRC, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            p = line.split("|")
            kind = p[0]
            if kind == "CASE":
                case["title"], case["victim"], case["intro"] = p[1], p[2], p[3]
            elif kind == "SOLUTION":
                case["solution"] = p[1]
            elif kind == "CULPRIT":
                case["culpritId"] = int(p[1])
            elif kind == "SUSPECT":
                case["suspects"].append(
                    {"id": int(p[1]), "name": p[2], "role": p[3], "description": p[4]})
            elif kind == "NODE":
                case["nodes"].append({
                    "id": int(p[1]), "parent": int(p[2]), "side": p[3], "type": p[4],
                    "title": p[5], "description": p[6],
                    "pointsTo": id_list(p[7]), "clears": id_list(p[8])})
            else:
                raise ValueError("Unknown record type: " + kind)

    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(case, f, indent=2, ensure_ascii=False)
        f.write("\n")

    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by dataset/make_website_data.py from dataset/case_haveli.txt\n")
        f.write("// Do not edit by hand: edit the .txt file and run the script again.\n")
        f.write("window.DMG = window.DMG || {};\n")
        f.write("DMG.caseData = " + json.dumps(case, indent=2, ensure_ascii=False) + ";\n")

    print("Wrote", os.path.normpath(OUT_JSON))
    print("Wrote", os.path.normpath(OUT_JS))
    print("Nodes:", len(case["nodes"]), " Suspects:", len(case["suspects"]))


if __name__ == "__main__":
    main()
