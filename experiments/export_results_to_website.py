"""
export_results_to_website.py
----------------------------
Copies the numbers measured by the C++ program (experiments/*.csv) into
website/js/cppResults.js so the Statistics page can display them.
Nothing is edited or invented: the CSV rows are copied exactly as written.

Run it again after you re-run the C++ experiments:
    python experiments/export_results_to_website.py
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "website", "js", "cppResults.js")


def read_rows(name):
    path = os.path.join(HERE, name)
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


data = {
    "experiment": read_rows("experiment_results.csv"),
    "scaling": read_rows("scaling_results.csv"),
}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by experiments/export_results_to_website.py from the C++ CSV files.\n")
    f.write("window.DMG = window.DMG || {};\n")
    f.write("DMG.cppResults = " + json.dumps(data, indent=2) + ";\n")

print("Wrote", os.path.normpath(OUT))
print("Experiment rows:", len(data["experiment"]), " Scaling rows:", len(data["scaling"]))
